/** Generates one module and never removes anything outside `<out>/<name>`. */
export function generateModule(options: CreateModuleOptions): ModuleGenerationResult {
  const resolved = validateModuleOptions(options);
  const modulePath = path.resolve(resolved.out, resolved.name);
  if (existsSync(modulePath)) {
    if (!resolved.force) {
      throw new GenerationError(
        `module destination ${modulePath} already exists; pass --force to recreate only this module`,
      );
    }
    rmSync(modulePath, { recursive: true, force: true });
  }

  const files = generatedFiles(resolved);
  for (const [relativePath, source] of Object.entries(files).sort(([left], [right]) =>
    left.localeCompare(right),
  )) {
    const destination = path.join(modulePath, relativePath);
    mkdirSync(path.dirname(destination), { recursive: true });
    writeFileSync(destination, source, "utf8");
  }
  mkdirSync(modulePath, { recursive: true });

  return { modulePath, files: Object.keys(files).sort() };
}

const USAGE = `usage: bun generator/src/create-module.ts --name=<kebab-name> --scope=<global|user|tenant> [--crud] [--events] [--audit] [--out=<parent>] [--force]`;

function main(): void {
  try {
    const result = generateModule(parseModuleArgs(process.argv.slice(2)));
    console.log(`generated ${result.files.length} files in ${result.modulePath}`);
  } catch (error) {
    if (error instanceof GenerationError) {
      console.error(`error: ${error.message}`);
      console.error(USAGE);
      process.exit(1);
    }
    throw error;
  }
}

