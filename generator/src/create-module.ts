export type ModuleScope = "global" | "user" | "tenant";

export interface CreateModuleOptions {
  name: string;
  scope: ModuleScope;
  crud?: boolean;
  events?: boolean;
  audit?: boolean;
  out?: string;
  force?: boolean;
}

interface ResolvedModuleOptions {
  name: string;
  scope: ModuleScope;
  crud: boolean;
  events: boolean;
  audit: boolean;
  out: string;
  force: boolean;
}

